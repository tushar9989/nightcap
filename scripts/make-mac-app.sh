#!/bin/bash
# Builds Marquee.app: double-click it to start the Marquee engine (if it is
# not already running) and open the app window.
#
#   scripts/make-mac-app.sh            -> ~/Applications/Marquee.app
#   scripts/make-mac-app.sh /some/dir  -> /some/dir/Marquee.app
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NODE="$(command -v node || true)"
if [ -z "$NODE" ]; then
  echo "Node.js not found. Install it first (brew install node)." >&2
  exit 1
fi
DEST_DIR="${1:-$HOME/Applications}"
APP="$DEST_DIR/Marquee.app"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Marquee</string>
  <key>CFBundleDisplayName</key><string>Marquee</string>
  <key>CFBundleIdentifier</key><string>local.marquee.launcher</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>Marquee</string>
  <key>CFBundleIconFile</key><string>Marquee</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/Marquee" <<LAUNCHER
#!/bin/bash
# Generated by scripts/make-mac-app.sh
ROOT="$ROOT"
NODE="$NODE"
PORT="\${PORT:-8484}"
URL="http://localhost:\$PORT"
export PATH="/opt/homebrew/bin:/usr/local/bin:\$PATH"
if ! curl -fs "\$URL/api/ping" | grep -q marquee; then
  mkdir -p "\$ROOT/data"
  nohup "\$NODE" "\$ROOT/server/index.js" --no-open >> "\$ROOT/data/server.log" 2>&1 &
  for _ in \$(seq 1 100); do
    curl -fs "\$URL/api/ping" >/dev/null 2>&1 && break
    sleep 0.1
  done
fi
exec "\$NODE" "\$ROOT/server/window.js" "\$URL"
LAUNCHER
chmod +x "$APP/Contents/MacOS/Marquee"

# Icon: render the SVG with Quick Look, then build an .icns.
TMP="$(mktemp -d)"
if qlmanage -t -s 1024 -o "$TMP" "$ROOT/public/icon.svg" >/dev/null 2>&1 && [ -f "$TMP/icon.svg.png" ]; then
  SET="$TMP/Marquee.iconset"
  mkdir -p "$SET"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$TMP/icon.svg.png" --out "$SET/icon_${s}x${s}.png" >/dev/null
    sips -z $((s * 2)) $((s * 2)) "$TMP/icon.svg.png" --out "$SET/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$SET" -o "$APP/Contents/Resources/Marquee.icns" || true
fi
rm -rf "$TMP"
touch "$APP"

echo "Created $APP"
echo "Open it from Finder, Launchpad or Spotlight. Drag it to the Dock to keep it there."
