#!/bin/bash
# Builds Nightcap.app: double-click it to start Nightcap and open its window.
# Closing the window (or quitting/killing that browser) quits Nightcap and
# everything it runs; a Nightcap left over from older code is replaced.
#
#   scripts/make-mac-app.sh            -> ~/Applications/Nightcap.app
#   scripts/make-mac-app.sh /some/dir  -> /some/dir/Nightcap.app
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
NODE="$(command -v node || true)"
if [ -z "$NODE" ]; then
  echo "Node.js not found. Install it first (brew install node)." >&2
  exit 1
fi
DEST_DIR="${1:-$HOME/Applications}"
APP="$DEST_DIR/Nightcap.app"

rm -rf "$APP"
# The app was called Marquee before: remove that launcher if this script made it.
OLD="$DEST_DIR/Marquee.app"
if [ -f "$OLD/Contents/Info.plist" ] && grep -q "local.marquee.launcher" "$OLD/Contents/Info.plist"; then
  rm -rf "$OLD"
  echo "Removed the old $OLD"
fi
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Nightcap</string>
  <key>CFBundleDisplayName</key><string>Nightcap</string>
  <key>CFBundleIdentifier</key><string>local.nightcap.app</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>Nightcap</string>
  <key>CFBundleIconFile</key><string>Nightcap</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/Nightcap" <<LAUNCHER
#!/bin/bash
# Generated by scripts/make-mac-app.sh
ROOT="$ROOT"
NODE="$NODE"
PORT="\${PORT:-8484}"
URL="http://localhost:\$PORT"
export PATH="/opt/homebrew/bin:/usr/local/bin:\$PATH"
# The version of the server code on disk (CODE_STAMP in server/index.js).
CODE="\$(stat -f %m "\$ROOT"/server/*.js "\$ROOT/package.json" | sort -n | tail -1)"
PING="\$(curl -fs --max-time 2 "\$URL/api/ping" || true)"
# (Before the rename the engine answered as "marquee".)
if [[ "\$PING" == *'"app":"nightcap"'* || "\$PING" == *'"app":"marquee"'* ]]; then
  # Already running this code: open another window.
  if [[ "\$PING" == *"\"code\":\$CODE}"* ]] && curl -fs -X POST -H "Content-Type: application/json" -d "{}" "\$URL/api/window" >/dev/null; then exit 0; fi
  # Left over from older code: replace it.
  curl -fs -X POST -H "Content-Type: application/json" -d "{}" "\$URL/api/quit" >/dev/null || true
  for _ in \$(seq 1 50); do
    curl -fs --max-time 0.3 "\$URL/api/ping" >/dev/null 2>&1 || break
    sleep 0.1
  done
fi
mkdir -p "\$ROOT/data"
# The server opens the window itself and quits when it closes.
nohup "\$NODE" "\$ROOT/server/index.js" >> "\$ROOT/data/server.log" 2>&1 &
LAUNCHER
chmod +x "$APP/Contents/MacOS/Nightcap"

# Icon: render the SVG (Chrome keeps its transparent corners; Quick Look fills
# them white), then build an .icns.
TMP="$(mktemp -d)"
PNG=""
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
if [ -x "$CHROME" ]; then
  printf '<!doctype html><body style="margin:0;background:transparent"><img src="file://%s" style="display:block;width:1024px;height:1024px">' "$ROOT/public/icon.svg" > "$TMP/icon.html"
  "$CHROME" --headless=new --disable-gpu --hide-scrollbars --user-data-dir="$TMP/chrome" --default-background-color=00000000 \
    --window-size=1024,1024 --screenshot="$TMP/icon.png" "file://$TMP/icon.html" >/dev/null 2>&1 && [ -f "$TMP/icon.png" ] && PNG="$TMP/icon.png"
fi
if [ -z "$PNG" ] && qlmanage -t -s 1024 -o "$TMP" "$ROOT/public/icon.svg" >/dev/null 2>&1 && [ -f "$TMP/icon.svg.png" ]; then
  PNG="$TMP/icon.svg.png"
fi
if [ -n "$PNG" ]; then
  SET="$TMP/Nightcap.iconset"
  mkdir -p "$SET"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$PNG" --out "$SET/icon_${s}x${s}.png" >/dev/null
    sips -z $((s * 2)) $((s * 2)) "$PNG" --out "$SET/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$SET" -o "$APP/Contents/Resources/Nightcap.icns" || true
fi
rm -rf "$TMP"
touch "$APP"

echo "Created $APP"
echo "Open it from Finder, Launchpad or Spotlight. Drag it to the Dock to keep it there."
